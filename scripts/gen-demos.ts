// Writes src/gallery/demos.gen.ts: one import per src/kit/**/*.demo.tsx, so adding a component never touches the gallery.
// Run `bun run gen`; `dev` and `typecheck` run it first. The output is git-ignored.
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";

import { Glob } from "bun";

const SRC = new URL("../src/", import.meta.url).pathname;
const OUT = `${SRC}gallery/demos.gen.ts`;

/** The generated module for the given demo files (paths relative to src/), sorted so the output is stable. */
export function renderDemos(files: string[]): string {
  const sorted = [...files].sort();
  const imports = sorted.map((file, index) => `import demo${index} from "../${file}";`);
  const list = sorted.map((_, index) => `demo${index}`).join(", ");
  return `// Generated by scripts/gen-demos.ts; do not edit.\nimport type { Demo } from "../kit/demo.ts";\n${imports.join("\n")}\n\nexport const demos: Demo[] = [${list}];\n`;
}

if (import.meta.main) {
  const files = [...new Glob("kit/**/*.demo.tsx").scanSync(SRC)];
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, renderDemos(files));
  console.log(`gen-demos: ${files.length} demo(s)`);
}
